"""The hybrid ZUGFeRD PDF of an ATIV Gutschrift.

The Credit Note of a final ``purchase.order`` leaves the system as a PDF/A-3
file carrying the ``factur-x.xml`` of ``tools/facturx_builder.py`` as an
embedded file, plus the XMP metadata that makes a reader recognise it as a
Factur-X document. This module hooks the one place every route to that PDF goes
through -- ``ir.actions.report._render_qweb_pdf_prepare_streams`` -- so the
print button, both mail templates and the portal download all yield the very
same bytes without any of them knowing about e-invoicing.

Generated once, served from storage afterwards: the first render converts and
stores the result on the order, every later render replaces its freshly
rendered stream with the stored file. That is what makes the PDF the customer
received and the PDF the portal serves byte-identical, and it is why the
regeneration paths in ``purchase_order.py`` clear
``ativ_erechnung_pdf_file`` rather than re-rendering on top of it.

Served from storage only while the stored file still *is* the document the
data describes, though. The ``write()`` hooks in ``purchase_order.py`` and
``purchase_order_line.py`` notice a change to the order or its lines at the
moment it happens, which is the fast, immediate feedback a user editing an
order gets -- but they can only watch the fields of those two models, and the
payload also reads master data that lives elsewhere: the issuer contact's
address, VAT id and bank account on ``res.partner``, edited in the Contacts
app with nothing on the order changing at all. This module's override is the
second, slower net underneath them, and it catches what they structurally
cannot see: because every send, download and print comes through here, the
payload is rebuilt and compared with the stored one on each of them
(``_ativ_erechnung_build_xml``), and a difference means the stored file is
stale -- rebuilt while the Gutschrift has not been sent, refused outright once
it has.

Scope is deliberately narrow: only ``purchase.report_purchaseorder`` of an order
in state ``purchase`` with the feature switched on is ever touched. The
quotation report, a draft order's PDF and every other report in the database
come out of the override exactly as the core built them.
"""

import base64
import datetime
import io
import logging

from lxml import etree
from markupsafe import escape

from odoo import _, fields, models
from odoo.addons.ativ_greenrx.tools import facturx_builder
from odoo.exceptions import UserError
from odoo.tools.pdf import OdooPdfFileReader, OdooPdfFileWriter

_logger = logging.getLogger(__name__)

# The Credit Note report. ``purchase.report_purchasequotation`` is deliberately
# absent: a quotation is not a Gutschrift and carries no e-invoice.
CREDIT_NOTE_REPORT_NAME = "purchase.report_purchaseorder"

# Fixed by the Factur-X specification: the embedded file must carry this exact
# name for a reader to find the e-invoice.
FACTURX_FILENAME = "factur-x.xml"

# PDF/A-3 requires the embedded XML to be declared as an alternative
# representation of the page content rather than as a mere data file.
FACTURX_AFRELATIONSHIP = "/Alternative"

# The XMP packet of a Factur-X document, from Odoo's own
# ``account_edi_ubl_cii.account_invoice_pdfa_3_facturx_metadata`` template,
# with two deliberate differences:
#   * no ``<?xpacket …?>`` header and footer -- ``add_file_metadata`` wraps the
#     content it is given in exactly those two, and a second pair inside the
#     packet is a PDF/A validation error;
#   * ``fx:ConformanceLevel`` is ``EN 16931`` and not core's ``EXTENDED``,
#     because ``facturx_builder`` builds the EN 16931 profile (its
#     ``GUIDELINE_ID``). The two have to agree: the XMP is what a reader
#     believes before it validates the XML.
# ``dc:description`` says "Credit note" for the same reason -- an ATIV
# e-Rechnung is a Gutschrift, never an invoice (the ``DocumentType`` of the
# extension schema stays ``INVOICE``: that is the Factur-X vocabulary for the
# document class as a whole, not a statement about this document's type code).
FACTURX_XMP_METADATA = """<x:xmpmeta xmlns:x="adobe:ns:meta/">
  <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
    <rdf:Description xmlns:pdfaid="http://www.aiim.org/pdfa/ns/id/" rdf:about="">
      <pdfaid:part>3</pdfaid:part>
      <pdfaid:conformance>A</pdfaid:conformance>
    </rdf:Description>
    <rdf:Description xmlns:dc="http://purl.org/dc/elements/1.1/" rdf:about="">
      <dc:title><rdf:Alt><rdf:li xml:lang="x-default">{title}</rdf:li></rdf:Alt></dc:title>
      <dc:creator><rdf:Seq><rdf:li>Odoo</rdf:li></rdf:Seq></dc:creator>
      <dc:description><rdf:Alt><rdf:li xml:lang="x-default">Credit note generated by Odoo</rdf:li></rdf:Alt></dc:description>
    </rdf:Description>
    <rdf:Description xmlns:pdf="http://ns.adobe.com/pdf/1.3/" rdf:about="">
      <pdf:Producer>Odoo</pdf:Producer>
    </rdf:Description>
    <rdf:Description xmlns:xmp="http://ns.adobe.com/xap/1.0/" rdf:about="">
      <xmp:CreatorTool>Odoo</xmp:CreatorTool>
      <xmp:CreateDate>{date}</xmp:CreateDate>
      <xmp:ModifyDate>{date}</xmp:ModifyDate>
    </rdf:Description>
    <rdf:Description xmlns:pdfaExtension="http://www.aiim.org/pdfa/ns/extension/" xmlns:pdfaSchema="http://www.aiim.org/pdfa/ns/schema#" xmlns:pdfaProperty="http://www.aiim.org/pdfa/ns/property#" rdf:about="">
      <pdfaExtension:schemas>
        <rdf:Bag>
          <rdf:li rdf:parseType="Resource">
            <pdfaSchema:schema>Factur-X PDFA Extension Schema</pdfaSchema:schema>
            <pdfaSchema:namespaceURI>urn:factur-x:pdfa:CrossIndustryDocument:invoice:1p0#</pdfaSchema:namespaceURI>
            <pdfaSchema:prefix>fx</pdfaSchema:prefix>
            <pdfaSchema:property>
              <rdf:Seq>
                <rdf:li rdf:parseType="Resource"><pdfaProperty:name>DocumentFileName</pdfaProperty:name><pdfaProperty:valueType>Text</pdfaProperty:valueType><pdfaProperty:category>external</pdfaProperty:category><pdfaProperty:description>name of the embedded XML invoice file</pdfaProperty:description></rdf:li>
                <rdf:li rdf:parseType="Resource"><pdfaProperty:name>DocumentType</pdfaProperty:name><pdfaProperty:valueType>Text</pdfaProperty:valueType><pdfaProperty:category>external</pdfaProperty:category><pdfaProperty:description>INVOICE</pdfaProperty:description></rdf:li>
                <rdf:li rdf:parseType="Resource"><pdfaProperty:name>Version</pdfaProperty:name><pdfaProperty:valueType>Text</pdfaProperty:valueType><pdfaProperty:category>external</pdfaProperty:category><pdfaProperty:description>The actual version of the Factur-X XML schema</pdfaProperty:description></rdf:li>
                <rdf:li rdf:parseType="Resource"><pdfaProperty:name>ConformanceLevel</pdfaProperty:name><pdfaProperty:valueType>Text</pdfaProperty:valueType><pdfaProperty:category>external</pdfaProperty:category><pdfaProperty:description>The conformance level of the embedded Factur-X data</pdfaProperty:description></rdf:li>
              </rdf:Seq>
            </pdfaSchema:property>
          </rdf:li>
        </rdf:Bag>
      </pdfaExtension:schemas>
    </rdf:Description>
    <rdf:Description xmlns:fx="urn:factur-x:pdfa:CrossIndustryDocument:invoice:1p0#" rdf:about="">
      <fx:ConformanceLevel>EN 16931</fx:ConformanceLevel>
      <fx:DocumentFileName>{filename}</fx:DocumentFileName>
      <fx:DocumentType>INVOICE</fx:DocumentType>
      <fx:Version>1.0</fx:Version>
    </rdf:Description>
  </rdf:RDF>
</x:xmpmeta>"""


class IrActionsReport(models.Model):
    _inherit = "ir.actions.report"

    def _render_qweb_pdf_prepare_streams(self, report_ref, data, res_ids=None):
        """Turn the Credit Note of a final order into its hybrid ZUGFeRD PDF.

        Hooked here rather than on each caller because this is the single
        chokepoint of every route to the PDF -- the print action, the two mail
        templates and the portal download all end up in it, and a hybrid PDF
        that only some of them produce is worse than none.

        Everything but ``purchase.report_purchaseorder`` of an order in state
        ``purchase``, with the feature switched on, is handed back exactly as
        the core produced it.

        An order that already carries a hybrid PDF gets it back unchanged only
        while its data still yields the very same payload; otherwise the file is
        stale, and this is where that is noticed (see the module docstring).
        A stale file is rebuilt and the chatter says so -- or, once the
        Gutschrift has been sent, the whole print / download / send is refused,
        because the frozen document and the data no longer agree and only a
        human can decide which of the two is wrong.
        """
        # EXTENDS base
        collected_streams = super()._render_qweb_pdf_prepare_streams(report_ref, data, res_ids=res_ids)

        if not (
            collected_streams
            and res_ids
            and self._get_report(report_ref).report_name == CREDIT_NOTE_REPORT_NAME
        ):
            return collected_streams

        # Read once, not per order: the switch is a single ``ir.config_parameter``
        # and an installation with the feature off must stay a plain no-op (R6).
        if not self.env["res.config.settings"]._ativ_erechnung_is_enabled():
            return collected_streams

        # Iterated over the streams and not over ``res_ids``: the core collects
        # one stream per *record*, so ``res_ids == [42, 42]`` yields a single
        # entry, and walking ``res_ids`` would convert that one stream twice and
        # embed two ``factur-x.xml`` files in it.
        for res_id, stream_data in collected_streams.items():
            # The core skips a record whose rendering produced nothing
            # (``_prepare_pdf_report_attachment_vals_list`` does the same check);
            # there is no PDF to convert in that case.
            if not stream_data["stream"]:
                continue
            order = self.env["purchase.order"].browse(res_id)
            # A draft or sent order is a Request for Quotation, not a Gutschrift:
            # its PDF carries no XML (R1).
            if order.state != "purchase":
                continue

            # ``bin_size=False`` is what makes this the file and not its size: a
            # Binary attachment field is context-dependent and returns the
            # human-readable file size whenever ``bin_size`` is in the context,
            # which a report printed from a form view can very well carry.
            stored_pdf = order.with_context(bin_size=False).ativ_erechnung_pdf_file
            if stored_pdf:
                # Not "there is a stored file" but "the stored file is still the
                # document the data describes": the payload is rebuilt from the
                # order and the issuer as they are right now and compared with
                # the one the stored file carries. This is the net under the
                # ``write()`` hooks of ``purchase_order.py`` -- see the module
                # docstring -- and it sits here because every route to the PDF
                # goes through this method.
                stored_xml = self._ativ_erechnung_stored_xml(stored_pdf)
                # Rebuilt with the issue date the stored payload itself carries
                # rather than with one resolved again, because that date is the
                # *reader's* (see ``_ativ_erechnung_issue_date``): re-resolving
                # it would make one and the same untouched order read as changed
                # to a reader on the other side of a day boundary, and refuse
                # the download of an already sent Gutschrift to everybody
                # outside the timezone it was confirmed in. Handing the stored
                # date back in leaves the comparison about the data alone. A
                # payload whose date cannot be read (``None``) falls through to
                # the "changed" branch below -- the rebuilt bytes can then only
                # differ -- which is the same fail-safe direction as a stored
                # file carrying no payload at all.
                fresh_xml = self._ativ_erechnung_build_xml(
                    order, issue_date=self._ativ_erechnung_stored_issue_date(stored_xml)
                )
                if fresh_xml == stored_xml:
                    # Generated once, served identically ever after (R4).
                    stream_data["stream"].close()
                    stream_data["stream"] = io.BytesIO(base64.b64decode(stored_pdf))
                    continue
                # The data moved after the Gutschrift left the system: the bytes
                # the recipient holds are the document, and these are no longer
                # them. Refused rather than quietly served or rebuilt -- the
                # same rule ``_ativ_erechnung_check_not_sent`` applies to a
                # write, applied to a read for the same reason (R5), and the
                # only remaining way out is a human undoing the change.
                if order.ativ_erechnung_sent:
                    raise UserError(_(
                        "Cannot serve the e-Rechnung of %(name)s: the underlying "
                        "data changed after it was already sent, and a sent "
                        "e-Rechnung cannot be regenerated.",
                        name=order.display_name,
                    ))
                # Not sent yet: it is rebuilt below, from the stream the core
                # has just rendered rather than from the stored bytes -- the
                # changed master data is on the printed page as well, not only
                # in the payload.

            hybrid_pdf = self._ativ_erechnung_build_hybrid_pdf(
                order, stream_data["stream"].getvalue()
            )
            stream_data["stream"].close()
            stream_data["stream"] = io.BytesIO(hybrid_pdf)
            # sudo(): this override runs inside whatever context asked for the
            # report -- a portal download or a mail send by a non-admin user --
            # and a system-generated attachment must be stored regardless of the
            # caller's own write access to ``purchase.order``; this is how the
            # core stores ``invoice_pdf_report_file`` too. The context key is
            # the opt-out of the protected-fields guard in ``purchase_order.py``,
            # which otherwise refuses any write to this field.
            order.sudo().with_context(ativ_erechnung_internal_write=True).write({
                "ativ_erechnung_pdf_file": base64.b64encode(hybrid_pdf),
            })
            if stored_pdf:
                # A stale file was just replaced, and the chatter is where the
                # person who sends the Gutschrift finds out. Word for word the
                # note of ``purchase_order._ativ_erechnung_on_relevant_change``:
                # to a reader the two are the same event, noticed at a different
                # moment, and two wordings would suggest two different things
                # happened. sudo() for the reason the write above gives -- a
                # note recording a system action must not depend on the caller's
                # own access to the order's chatter.
                order.sudo().message_post(
                    body=_("E-Rechnung regenerated: the underlying data changed.")
                )

        return collected_streams

    def _ativ_erechnung_build_xml(self, order, issue_date=None):
        """Return the ``factur-x.xml`` payload of ``order`` as its data stands now.

        The one place the payload is built from an order, so that what the
        staleness check above compares is built exactly like what was embedded
        in the stored file: built in two places, the two would drift apart and
        every single render would read as a data change.

        That comparison is byte equality, and this method is what makes it
        meaningful -- ``build_facturx_xml`` is a pure mapping of its three
        arguments, so the same order, issuer and issue date always produce the
        same bytes and any difference is a real change in the data. Two of those
        three are the order's own; the issue date is not, because it is resolved
        in the *reader's* timezone (``_ativ_erechnung_issue_date``), and that is
        what ``issue_date`` is for. The staleness check hands in the date the
        stored payload already carries, so the rebuilt bytes differ from the
        stored ones only where the data really does -- without it, the same
        untouched order would read as changed to a reader on the other side of a
        day boundary, which on a sent Gutschrift means refusing to serve it at
        all. ``None`` -- a first generation, or a genuine regeneration -- stamps
        the document as of now, which is the one moment resolving the date
        afresh is the right thing to do.

        ``_check_ativ_erechnung_data`` runs first, for the orders confirmation
        time never saw: one confirmed before the feature was switched on, or one
        whose issuer contact was emptied afterwards. Without it the mapping
        would fail on an empty issuer with a bare "Expected singleton" instead
        of naming the field that is missing.
        """
        # sudo(): this is a system integrity check, not a read on the caller's
        # behalf. Every print, download and send comes through here, including a
        # portal user downloading their own Gutschrift, and the payload is built
        # from internal master data that user has no business reading -- the
        # issuer contact and its bank account (``res.partner.bank`` is readable
        # by internal users only). Being served the file that was built for them
        # must not depend on access to the data it was built from. Same
        # reasoning as the write and the chatter note in the override above.
        # ``sudo()`` flips superuser mode without changing ``env.uid``, so the
        # issue date below is still resolved in the reader's own timezone.
        order = order.sudo()
        order._check_ativ_erechnung_data()
        issuer = self.env["res.config.settings"].sudo()._ativ_erechnung_get_issuer_partner()
        if issue_date is None:
            issue_date = self._ativ_erechnung_issue_date(order)
        return facturx_builder.build_facturx_xml(order, issuer, issue_date)

    def _ativ_erechnung_issue_date(self, order):
        """Return the issue date of ``order``'s e-Rechnung, as the report prints it.

        The reader's date, not the builder's: ``date_order`` is stored in UTC
        while the report prints it in the reader's timezone, so a late-evening
        order would otherwise carry one calendar day on the page and another in
        the XML. Shared by the payload and the XMP packet, which state the same
        date and must not be able to state two.
        """
        return fields.Datetime.context_timestamp(order, order.date_order).date()

    def _ativ_erechnung_stored_xml(self, stored_pdf):
        """Return the ``factur-x.xml`` embedded in ``stored_pdf``, or ``None``.

        Looked up by name because this feature is not the only thing embedding a
        file in a purchase order's PDF: core's ``purchase`` addon attaches its
        own UBL Order XML to every render of this report, and that file is none
        of this feature's business.

        ``None`` for a stored file this cannot read a payload out of -- one
        carrying none, and one that cannot be decoded or parsed at all --
        which the caller reads as "does not match", the fail-safe direction: a
        stored e-Rechnung whose payload cannot be found is not one to go on
        serving. A corrupted stored file must reach the caller as that same
        verdict and not as a traceback: it is rebuilt while the Gutschrift has
        not been sent, and refused with the feature's own message once it has,
        where an uncaught parse error would instead break every print,
        download and send of the order with nothing a user can act on.
        """
        try:
            reader = OdooPdfFileReader(io.BytesIO(base64.b64decode(stored_pdf)), strict=False)
            for name, content in reader.getAttachments():
                if name == FACTURX_FILENAME:
                    return content
        except Exception:  # noqa: BLE001
            # Deliberately broad, for the two reasons core's own
            # ``OdooPdfFileReader.getAttachments`` catches ``Exception`` around
            # its traversal with a "malformed pdf" comment: the exception
            # surface is not a fixed set -- ``odoo.tools.pdf`` binds pypdf,
            # PyPDF2 2.x or PyPDF2 1.x, whichever imports on the host, and a
            # damaged document fails in whichever of them wherever it was
            # truncated (the reader's constructor, a decompressed stream, a
            # missing dictionary key) -- and this method's whole contract is
            # that unreadable input yields a verdict rather than an error.
            # Logged with its traceback because the corruption itself is a real
            # problem, and regenerating the file is what hides it from the user.
            _logger.warning(
                "The stored e-Rechnung PDF cannot be read and is treated as "
                "stale; its contents may be corrupted.",
                exc_info=True,
            )
        return None

    def _ativ_erechnung_stored_issue_date(self, stored_xml):
        """Return the issue date ``stored_xml`` states, or ``None``.

        What the staleness check rebuilds with, read back out of the very
        document it is about to compare against rather than resolved again: the
        issue date is the reader's (``_ativ_erechnung_issue_date``), so a date
        resolved here would say as much about who is looking as about the order,
        and two readers either side of a day boundary would disagree about a
        Gutschrift neither of them touched.

        ``None`` for a payload this cannot read a date out of -- absent,
        unparseable, or not XML at all -- which the caller reads as "does not
        match", the same fail-safe direction ``_ativ_erechnung_stored_xml``
        takes: a stored e-Rechnung that cannot be compared with its data is not
        one to go on serving.
        """
        if not stored_xml:
            return None
        try:
            document = etree.fromstring(stored_xml)
        except etree.XMLSyntaxError:
            return None
        # The one element of the payload stating the document's own date; the
        # namespaces and the format come from the builder that wrote it, so the
        # two cannot drift apart.
        text = document.findtext(
            "rsm:ExchangedDocument/ram:IssueDateTime/udt:DateTimeString",
            namespaces=facturx_builder.NSMAP,
        )
        if not text:
            return None
        try:
            return datetime.datetime.strptime(
                text, facturx_builder.DATE_PATTERN_102
            ).date()
        except ValueError:
            return None

    def _ativ_erechnung_build_hybrid_pdf(self, order, pdf_content):
        """Return the PDF/A-3 bytes of ``pdf_content`` carrying ``order``'s e-invoice.

        Pure byte surgery on a rendered PDF: no ORM write, no stream of the
        caller touched, so the caller stays in charge of what happens to the
        result.

        A failure is reported, never swallowed: it aborts the transaction it
        runs in -- which, on the confirmation path, is the one confirming the
        order -- and that is the intended outcome. A final Gutschrift without a
        valid e-Rechnung must not come into existence, and a PDF whose XMP
        claims an EN 16931 conformance it does not have would be worse than an
        error message. The core, which embeds Factur-X as a convenience rather
        than as the point of the document, logs and carries on instead.
        """
        # Built -- and the order therefore validated, which
        # ``_ativ_erechnung_build_xml`` does for it -- before a single page is
        # converted: the PDF/A-3 conversion is the expensive half of this method
        # and an order that fails validation is rejected either way, and a
        # conversion error on such an order would mask the configuration
        # problem that is the actual cause.
        xml_bytes = self._ativ_erechnung_build_xml(order)

        reader = OdooPdfFileReader(io.BytesIO(pdf_content), strict=False)
        writer = OdooPdfFileWriter()
        writer.cloneReaderDocumentRoot(reader)
        try:
            writer.convert_to_pdfa()
        except Exception as error:
            # The conversion reads structures the core takes for granted in a
            # wkhtmltopdf document -- an outlines dictionary, a font resource
            # with its descendants on every page -- and raises a bare KeyError
            # on a PDF that lacks one. Re-raised as a UserError so the person
            # who pressed the button reads which document failed instead of a
            # traceback, with the traceback itself kept in the log.
            _logger.exception("PDF/A-3 conversion failed for %s", order.display_name)
            raise UserError(_(
                "The e-Rechnung of %(name)s could not be built: its PDF cannot be "
                "converted to PDF/A-3 (%(error)s).",
                name=order.display_name,
                error=error,
            )) from error

        writer.add_attachment(
            FACTURX_FILENAME,
            xml_bytes,
            subtype="text/xml",
            afrelationship=FACTURX_AFRELATIONSHIP,
        )

        # ``order.name`` reaches the XMP as text, so it is escaped: the document
        # number is free-form and a stray ``&`` would break the packet.
        xmp_metadata = FACTURX_XMP_METADATA.format(
            title=escape(order.name),
            # The same date the payload above carries, from the same helper: the
            # two are read as statements about one document.
            date=self._ativ_erechnung_issue_date(order).isoformat(),
            filename=FACTURX_FILENAME,
        )
        writer.add_file_metadata(xmp_metadata.encode())

        new_stream = io.BytesIO()
        writer.write(new_stream)
        hybrid_pdf = new_stream.getvalue()
        new_stream.close()
        return hybrid_pdf
